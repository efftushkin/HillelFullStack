'use strict';

// Escapes characters that are meaningful in HTML to prevent stored/reflected XSS
// when echoing user-supplied input back into a generated page.
function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

module.exports = { escapeHtml };
